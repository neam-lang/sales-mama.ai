// Parses the generated book pages (scripts/build_books.py) for the bento rail.
// The pages are markdown views; this reads only the lines that script writes.

export interface AccountLine { id: string; name: string; tier: string; detail: string }
export interface DueLine { id: string; name: string; tier: string; due: string; overdue: boolean; action: string; nba: string; why: string }

export interface Book {
  name: string;
  rep: string;
  role: string;
  markets: string[];
  active: number;
  capacity: number | null;
  tiers: { A: number; B: number; C: number };
  meetings: { done: number; target: number | null };
  replies7d: { replies: number; sent: number };
  quota: number | null;
  generated: string;
  due: DueLine[];
  hot: AccountLine[];
  atRisk: AccountLine[];
  vam: AccountLine[];
  pipeline: { stage: string; n: number }[];
}

export interface TeamBook {
  generated: string;
  reps: number;
  pool: { total: number; A: number; B: number; C: number };
  review: number;
}

const num = (s: string | undefined): number | null => (s == null || s === '-' ? null : Number(s));

export function parseBook(md: string): Book {
  const line = (re: RegExp) => re.exec(md) ?? [];
  const [, name = ''] = line(/^# Book — (.+)$/m);
  const [, rep = '', role = 'rep', markets = ''] = line(/^- Rep: `([^`]+)` · role (\S+) · markets (.+)$/m);
  const [, active = '0', cap] = line(/^- Active accounts: \*\*(\d+) \/ ([\d-]+)\*\*/m);
  const [, mix = ''] = line(/^- Tier mix \(active\): (.+)$/m);
  const [, mDone = '0', mTarget] = line(/^- Meetings this month: \*\*(\d+) \/ ([\d-]+)\*\*/m);
  const [, replies = '0', sent = '0'] = line(/^- Last 7 days: \*\*(\d+) replies \/ (\d+) sent\*\*/m);
  const [, quota] = line(/^- Daily quota: ([\d-]+)/m);
  const [, generated = ''] = line(/^_Generated by .+ at ([\d-]+ [\d:]+)\./m);
  const tier = (t: string) => Number(new RegExp(`\\b${t} (\\d+)`).exec(mix)?.[1] ?? 0);
  return {
    name, rep, role,
    markets: markets === '-' ? [] : markets.split(',').map(s => s.trim()).filter(Boolean),
    active: Number(active), capacity: num(cap),
    tiers: { A: tier('A'), B: tier('B'), C: tier('C') },
    meetings: { done: Number(mDone), target: num(mTarget) },
    replies7d: { replies: Number(replies), sent: Number(sent) },
    quota: num(quota), generated,
    due: dueRows(section(md, 'Today')),
    hot: accountLines(section(md, 'Hot')),
    atRisk: accountLines(section(md, 'At risk')),
    vam: accountLines(section(md, 'VAM pre-drafts waiting')),
    pipeline: tableRows(section(md, 'Pipeline by stage'))
      .filter(r => r[0] !== '-').map(([stage, n]) => ({ stage, n: Number(n) })),
  };
}

export function parseTeam(md: string): TeamBook {
  const [, generated = ''] = /^_Generated by .+ at ([\d-]+ [\d:]+)\./m.exec(md) ?? [];
  const pool = section(md, 'Pool');
  const [, total = '0'] = /^## Pool \(unowned, active\): (\d+)/m.exec(md) ?? [];
  const t = (k: string) => Number(new RegExp(`\\b${k} (\\d+)`).exec(pool)?.[1] ?? 0);
  const [, review = '0'] = /^## Review queue: (\d+) undecided/m.exec(md) ?? [];
  const reps = tableRows(section(md, 'Reps')).filter(r => !r[0].startsWith('_')).length;
  return { generated, reps, pool: { total: Number(total), A: t('A'), B: t('B'), C: t('C') }, review: Number(review) };
}

/** Body of the `## <heading…>` section, up to the next `## `. */
function section(md: string, heading: string): string {
  const start = md.search(new RegExp(`^## ${heading.replace(/[()]/g, '\\$&')}\\b.*$`, 'm'));
  if (start < 0) return '';
  const rest = md.slice(start).split('\n').slice(1).join('\n');
  const end = rest.search(/^## /m);
  return end < 0 ? rest : rest.slice(0, end);
}

function accountLines(body: string): AccountLine[] {
  const out: AccountLine[] = [];
  for (const m of body.matchAll(/^- \[\[accounts\/([^\]]+)\]\] (.+?) · tier (\S+)(?: · (.*))?$/gm)) {
    out.push({ id: m[1], name: m[2], tier: m[3], detail: m[4] ?? '' });
  }
  return out;
}

function dueRows(body: string): DueLine[] {
  return tableRows(body).flatMap(cells => {
    const m = /^\[\[accounts\/([^\]]+)\]\] (.+)$/.exec(cells[0] ?? '');
    if (!m) return [];
    const [, tier = '', due = '', action = '', nba = '', why = ''] = cells;
    return [{ id: m[1], name: m[2], tier, due: due.replace(' (overdue)', ''), overdue: due.includes('overdue'), action, nba, why }];
  });
}

function tableRows(body: string): string[][] {
  return body.split('\n')
    .filter(l => l.startsWith('|') && !/^\|[-| ]+\|$/.test(l))
    .slice(1) // header
    .map(l => l.slice(1, -1).split(' | ').map(c => c.trim()));
}
