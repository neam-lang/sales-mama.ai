"""Rebuild wiki/index.md, the generated map of the wiki (gitignored).

Contents:
- counts of accounts by stage, tier and owner
- accounts grouped by owner, one line each:
  id, name, market, tier, stage, next_action_due
- events
- response library (objections, patterns, FAQ) by status
- contacts count

Run at every session start (session_start.py does it) and after any ingest:

    python3 scripts/build_index.py            # write wiki/index.md
    python3 scripts/build_index.py --stdout   # print instead of writing
"""
from __future__ import annotations

import argparse
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from mama_common import (  # noqa: E402
    STAGES, TIERS, iter_pages, norm, now_stamp, repo_root, setup_stdout, stage_rank,
    tier_rank, to_date, write_text,
)

LIBRARY_TYPES = ("objection", "pattern", "faq")


def _cell(v) -> str:
    s = norm(v)
    return s.replace("|", "/") if s else "-"


def render(root: Path) -> str:
    accounts = list(iter_pages("account", root))
    contacts = list(iter_pages("contact", root))
    events = list(iter_pages("event", root))
    library = [p for p in iter_pages(None, root)
               if p.meta is not None and (p.type in LIBRARY_TYPES or p.rel.startswith("wiki/responses/"))]

    by_stage = Counter(norm(p.meta.get("stage")) or "(none)" for p in accounts)
    by_tier = Counter(norm(p.meta.get("tier")).upper() or "(none)" for p in accounts)
    by_owner = Counter(norm(p.meta.get("owner")) or "(pool)" for p in accounts)

    out: list[str] = [
        "# Sales Mama index",
        "",
        f"_Generated by `scripts/build_index.py` at {now_stamp()}. Do not edit; it is rebuilt "
        "every session._",
        "",
        f"Accounts: **{len(accounts)}** · Contacts: **{len(contacts)}** · "
        f"Events: **{len(events)}** · Library pages: **{len(library)}**",
        "",
        "## Accounts by stage",
        "",
    ]
    stage_keys = sorted(by_stage, key=lambda s: (stage_rank(s), s))
    if stage_keys:
        out += ["| Stage | Count |", "|---|---|"]
        out += [f"| {s} | {by_stage[s]} |" for s in stage_keys]
    else:
        out.append("_No accounts yet._")

    out += ["", "## Accounts by tier", ""]
    tier_keys = sorted(by_tier, key=lambda t: (TIERS.index(t) if t in TIERS else 9, t))
    if tier_keys:
        out += ["| Tier | Count |", "|---|---|"]
        out += [f"| {t} | {by_tier[t]} |" for t in tier_keys]
    else:
        out.append("_No accounts yet._")

    out += ["", "## Accounts by owner", ""]
    owner_keys = sorted(by_owner, key=lambda o: (o == "(pool)", o))
    if owner_keys:
        out += ["| Owner | Count |", "|---|---|"]
        out += [f"| {o} | {by_owner[o]} |" for o in owner_keys]
    else:
        out.append("_No accounts yet._")

    out += ["", "## Accounts", ""]
    grouped: dict[str, list] = defaultdict(list)
    for p in accounts:
        grouped[norm(p.meta.get("owner")) or "(pool)"].append(p)
    if not grouped:
        out.append("_No accounts yet._")
    for owner in owner_keys:
        out += [f"### {owner}", ""]
        rows = sorted(grouped[owner], key=lambda p: (
            tier_rank(p.meta), to_date(p.meta.get("next_action_due")) or to_date("9999-12-31"),
            p.id))
        for p in rows:
            m = p.meta
            out.append(
                f"- [[accounts/{p.id}]] {_cell(m.get('name'))} · {_cell(m.get('market'))} · "
                f"tier {_cell(m.get('tier'))} · {_cell(m.get('stage'))} · "
                f"due {_cell(m.get('next_action_due'))}")
        out.append("")

    out += ["## Events", ""]
    if events:
        for p in sorted(events, key=lambda p: p.id):
            m = p.meta
            dates = m.get("dates") or []
            dates_s = ", ".join(str(d) for d in dates) if isinstance(dates, list) else norm(dates)
            matched = m.get("matched_accounts") or []
            n = len(matched) if isinstance(matched, list) else 0
            out.append(f"- [[events/{p.id}]] {_cell(m.get('name'))} · {_cell(m.get('market'))} · "
                       f"{dates_s or '-'} · {n} matched")
    else:
        out.append("_No events yet._")

    out += ["", "## Response library", ""]
    if library:
        lib = Counter((p.type or "page", norm(p.meta.get("status")) or "(none)") for p in library)
        out += ["| Type | Status | Count |", "|---|---|---|"]
        out += [f"| {t} | {s} | {n} |" for (t, s), n in sorted(lib.items())]
        out.append("")
        for p in sorted(library, key=lambda p: p.rel):
            title = norm(p.meta.get("title")) or p.id
            out.append(f"- [[{p.rel[len('wiki/'):-3]}]] {title} · {p.type or 'page'} · "
                       f"{norm(p.meta.get('status')) or '-'}")
    else:
        out.append("_No library pages yet._")

    out += ["", "## Contacts", "", f"{len(contacts)} contact page(s) in `wiki/contacts/`.", ""]
    return "\n".join(out)


def build(root: Path | None = None) -> Path:
    """Write wiki/index.md and return its path."""
    root = root or repo_root()
    path = root / "wiki" / "index.md"
    write_text(path, render(root))
    return path


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Rebuild wiki/index.md (generated, gitignored).")
    ap.add_argument("--stdout", action="store_true", help="print the index instead of writing it")
    args = ap.parse_args(argv)
    setup_stdout()
    root = repo_root()
    if args.stdout:
        print(render(root))
    else:
        path = build(root)
        print(f"Wrote {path.relative_to(root).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
