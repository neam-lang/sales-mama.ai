"""Rebuild the books: wiki/books/<rep>.md for every rep and wiki/books/team.md.

Books are generated views (gitignored) per PLAN.md §11. Each rep book shows:
- active accounts vs max_active, tier mix
- meetings this month (log/touches.csv status meeting_booked / meeting_held,
  distinct accounts) vs targets.meetings_per_month
- replies vs sent in the last 7 days
- today: due and overdue actions (sorted by tier, then due date) with nba /
  nba_reason; hot accounts; at-risk accounts; VAM pre-drafts waiting
- pipeline counts by stage; handed over this month

The team book has a per-rep table plus the pool (unowned accounts) by tier,
the review-queue size and the funnel.

Missing fields are tolerated everywhere. Env MAMA_TODAY=YYYY-MM-DD fixes
"today" for tests.

    python3 scripts/build_books.py              # all books
    python3 scripts/build_books.py --rep mei    # one rep book (plus team)
"""
from __future__ import annotations

import argparse
import datetime as dt
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from mama_common import (  # noqa: E402
    STAGES, TIERS, has_vam_predraft, is_active, is_hot, iter_pages, load_reps, load_touches,
    norm, now_stamp, read_csv, repo_root, risk_flags, setup_stdout, stage_rank, tier_rank,
    to_date, today, write_text,
)

MEETING_STATUSES = {"meeting_booked", "meeting_held"}
FAR = dt.date(9999, 12, 31)


def _int(v, default: int | None = None) -> int | None:
    try:
        return int(v)
    except (TypeError, ValueError):
        return default


def _target(rep: dict) -> int | None:
    t = rep.get("targets")
    return _int(t.get("meetings_per_month")) if isinstance(t, dict) else None


def _c(v) -> str:
    s = norm(v)
    return s.replace("|", "/").replace("\n", " ") if s else "-"


def rep_stats(rep: dict, accounts: list, touches: list[dict], on: dt.date) -> dict:
    """Numbers for one rep. `accounts` are Page objects owned by the rep."""
    keys = {norm(rep.get("id")).lower(), norm(rep.get("email")).lower()} - {""}
    mine_t = [t for t in touches if norm(t.get("rep")).lower() in keys]
    week_start = on - dt.timedelta(days=6)
    month_start = on.replace(day=1)

    def in_range(t, start):
        d = to_date(t.get("ts"))
        return d is not None and start <= d <= on

    meetings = {norm(t.get("account")) or f"row{i}" for i, t in enumerate(mine_t)
                if norm(t.get("status")) in MEETING_STATUSES and in_range(t, month_start)}
    sent_7 = sum(1 for t in mine_t if norm(t.get("status")) == "sent" and in_range(t, week_start))
    replies_7 = sum(1 for t in mine_t if norm(t.get("status")) == "replied" and in_range(t, week_start))
    meetings_7 = sum(1 for t in mine_t
                     if norm(t.get("status")) in MEETING_STATUSES and in_range(t, week_start))

    active = [p for p in accounts if is_active(p.meta)]
    tiers = Counter(norm(p.meta.get("tier")).upper() or "-" for p in active)
    stages = Counter(norm(p.meta.get("stage")) or "(none)" for p in accounts)
    due = sorted(
        [p for p in active if (to_date(p.meta.get("next_action_due")) or FAR) <= on],
        key=lambda p: (tier_rank(p.meta), to_date(p.meta.get("next_action_due")) or FAR, p.id))
    hot = sorted([p for p in active if is_hot(p.meta, on)], key=lambda p: (tier_rank(p.meta), p.id))
    at_risk = sorted([p for p in active if risk_flags(p.meta)], key=lambda p: (tier_rank(p.meta), p.id))
    vam = sorted([p for p in active if has_vam_predraft(p.body)], key=lambda p: (tier_rank(p.meta), p.id))
    handed = [p for p in accounts if norm(p.meta.get("stage")) == "handed_over"
              and (to_date(p.meta.get("updated")) or dt.date.min) >= month_start]
    return {
        "active": len(active), "capacity": _int(rep.get("max_active")),
        "quota": _int(rep.get("daily_quota")), "tiers": tiers, "stages": stages,
        "meetings": len(meetings), "target": _target(rep),
        "sent_7": sent_7, "replies_7": replies_7, "meetings_7": meetings_7,
        "touches_7": sum(1 for t in mine_t if in_range(t, week_start)),
        "due": due, "hot": hot, "at_risk": at_risk, "vam": vam, "handed": handed,
    }


def render_rep(rep: dict, s: dict, on: dt.date) -> str:
    rid = norm(rep.get("id"))
    cap = s["capacity"]
    tier_mix = " · ".join(f"{t} {s['tiers'].get(t, 0)}" for t in TIERS)
    if s["tiers"].get("-"):
        tier_mix += f" · untiered {s['tiers']['-']}"
    tgt = s["target"]
    out = [
        f"# Book — {norm(rep.get('name')) or rid}",
        "",
        f"_Generated by `scripts/build_books.py` for {on.isoformat()} at {now_stamp()}. "
        "Do not edit._",
        "",
        f"- Rep: `{rid}` · role {norm(rep.get('role')) or 'rep'} · markets "
        f"{', '.join(str(m) for m in (rep.get('markets') or [])) or '-'}",
        f"- Active accounts: **{s['active']} / {cap if cap is not None else '-'}**"
        + (f" ({max(cap - s['active'], 0)} slots free)" if cap is not None else ""),
        f"- Tier mix (active): {tier_mix}",
        f"- Meetings this month: **{s['meetings']} / {tgt if tgt is not None else '-'}**",
        f"- Last 7 days: **{s['replies_7']} replies / {s['sent_7']} sent** · "
        f"{s['meetings_7']} meeting touches",
        f"- Daily quota: {s['quota'] if s['quota'] is not None else '-'}",
        f"- Handed over this month: {len(s['handed'])}",
        "",
        f"## Today — due actions ({len(s['due'])})",
        "",
    ]
    if s["due"]:
        out += ["| Account | Tier | Due | Next action | NBA | Why |", "|---|---|---|---|---|---|"]
        for p in s["due"]:
            m = p.meta
            d = to_date(m.get("next_action_due"))
            due = _c(m.get("next_action_due")) + (" (overdue)" if d and d < on else "")
            out.append(f"| [[accounts/{p.id}]] {_c(m.get('name'))} | {_c(m.get('tier'))} | {due} | "
                       f"{_c(m.get('next_action'))} | {_c(m.get('nba'))} | {_c(m.get('nba_reason'))} |")
    else:
        out.append("_Nothing due._")

    def lst(title, pages, extra):
        block = ["", f"## {title} ({len(pages)})", ""]
        block += [f"- [[accounts/{p.id}]] {_c(p.meta.get('name'))} · tier {_c(p.meta.get('tier'))}"
                  f" · {extra(p)}" for p in pages] or ["_None._"]
        return block

    out += lst("Hot", s["hot"], lambda p: f"score {_c(p.meta.get('score'))} "
               f"(updated {_c(p.meta.get('score_updated'))})")
    out += lst("At risk", s["at_risk"], lambda p: ", ".join(risk_flags(p.meta)))
    out += lst("VAM pre-drafts waiting", s["vam"], lambda p: f"nba {_c(p.meta.get('nba'))}")
    out += ["", "## Pipeline by stage", "", "| Stage | Count |", "|---|---|"]
    keys = sorted(s["stages"], key=lambda k: (stage_rank(k), k))
    out += [f"| {k} | {s['stages'][k]} |" for k in keys] or ["| - | 0 |"]
    out.append("")
    return "\n".join(out)


def render_team(reps: list[dict], stats: dict[str, dict], accounts: list, root: Path,
                on: dt.date) -> str:
    pool = [p for p in accounts if not norm(p.meta.get("owner")) and is_active(p.meta)]
    pool_t = Counter(norm(p.meta.get("tier")).upper() or "-" for p in pool)
    review = [r for r in read_csv(root / "log" / "review.csv") if not norm(r.get("decision"))]
    funnel = Counter(norm(p.meta.get("stage")) or "(none)" for p in accounts)
    out = [
        "# Team book",
        "",
        f"_Generated by `scripts/build_books.py` for {on.isoformat()} at {now_stamp()}. "
        "Do not edit._",
        "",
        "## Reps",
        "",
        "| Rep | Role | Markets | Active / cap | A | B | C | Sent 7d | Replies 7d | "
        "Meetings (month) / target | Due | At risk |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for rep in reps:
        s = stats[rep["id"]]
        cap = s["capacity"] if s["capacity"] is not None else "-"
        tgt = s["target"] if s["target"] is not None else "-"
        out.append(
            f"| [{rep['id']}]({rep['id']}.md) | {_c(rep.get('role'))} | "
            f"{', '.join(str(m) for m in (rep.get('markets') or [])) or '-'} | {s['active']} / {cap} | "
            f"{s['tiers'].get('A', 0)} | {s['tiers'].get('B', 0)} | {s['tiers'].get('C', 0)} | "
            f"{s['sent_7']} | {s['replies_7']} | {s['meetings']} / {tgt} | {len(s['due'])} | "
            f"{len(s['at_risk'])} |")
    if not reps:
        out.append("| _no reps yet_ | | | | | | | | | | | |")
    out += [
        "",
        f"## Pool (unowned, active): {len(pool)}",
        "",
        " · ".join(f"{t} {pool_t.get(t, 0)}" for t in TIERS)
        + (f" · untiered {pool_t['-']}" if pool_t.get("-") else ""),
        "",
    ]
    for p in sorted(pool, key=lambda p: (tier_rank(p.meta), p.id))[:20]:
        out.append(f"- [[accounts/{p.id}]] {_c(p.meta.get('name'))} · {_c(p.meta.get('market'))} · "
                   f"tier {_c(p.meta.get('tier'))} · score {_c(p.meta.get('score'))}")
    out += ["", f"## Review queue: {len(review)} undecided", "", "## Funnel", "",
            "| Stage | Count |", "|---|---|"]
    keys = sorted(funnel, key=lambda k: (stage_rank(k), k))
    out += [f"| {k} | {funnel[k]} |" for k in keys] or ["| - | 0 |"]
    out.append("")
    return "\n".join(out)


def build(root: Path | None = None, only: str | None = None) -> list[Path]:
    """Write the books; return the paths written."""
    root = root or repo_root()
    on = today()
    reps = load_reps(root)
    accounts = list(iter_pages("account", root))
    touches = load_touches(root)
    books = root / "wiki" / "books"
    books.mkdir(parents=True, exist_ok=True)
    stats: dict[str, dict] = {}
    written: list[Path] = []
    for rep in reps:
        mine = [p for p in accounts if norm(p.meta.get("owner")) == rep["id"]]
        stats[rep["id"]] = rep_stats(rep, mine, touches, on)
        if only and rep["id"] != only:
            continue
        path = books / f"{rep['id']}.md"
        write_text(path, render_rep(rep, stats[rep["id"]], on))
        written.append(path)
    team = books / "team.md"
    write_text(team, render_team(reps, stats, accounts, root, on))
    written.append(team)
    if not only:  # remove books of reps that no longer exist
        keep = {f"{r['id']}.md" for r in reps} | {"team.md"}
        for p in books.glob("*.md"):
            if p.name not in keep:
                try:
                    p.unlink()
                except OSError:
                    pass
    return written


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Rebuild wiki/books/<rep>.md and wiki/books/team.md.")
    ap.add_argument("--rep", help="rebuild only this rep's book (the team book is always rebuilt)")
    args = ap.parse_args(argv)
    setup_stdout()
    root = repo_root()
    for p in build(root, args.rep):
        print(f"Wrote {p.relative_to(root).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
